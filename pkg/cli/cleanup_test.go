func cleanupCLI(t *testing.T, args ...string) (string, error) {
	t.Helper()
	cmd := newCleanupCommand()
	var out bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&out)
	cmd.SilenceUsage = true
	cmd.SilenceErrors = true
	cmd.SetArgs(args)
	err := cmd.Execute()
	return out.String(), err
}
func cleanupCLIDirs(t *testing.T) (string, string, string) {
	t.Helper()
	if runtime.GOOS != "darwin" && runtime.GOOS != "linux" {
		t.Skip("POSIX cleanup fixture")
	}
	base, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("HOME", base)
	t.Setenv("XDG_CONFIG_HOME", filepath.Join(base, "config"))
	repo, target := filepath.Join(base, "repo"), filepath.Join(base, "generated")
	for _, path := range []string{repo, target} {
		if err := os.Mkdir(path, 0755); err != nil {
			t.Fatal(err)
		}
	}
	if out, err := exec.Command("git", "init", "-q", repo).CombinedOutput(); err != nil {
		t.Fatalf("fixture init: %s %v", out, err)
	}
	if err := os.WriteFile(filepath.Join(target, "payload"), []byte("generated bytes"), 0644); err != nil {
		t.Fatal(err)
	}
	return base, repo, target
}
func cleanupCLIReceipt(t *testing.T, base, repo, target string) string {
	t.Helper()
	out, err := cleanupCLI(t, "--record", "--kind", "scratch", "--disposable", "--path", target, "--repository", repo, "--owner", "task")
	if err != nil {
		t.Fatal(err)
	}
	path := filepath.Join(base, "receipt.json")
	if err := os.WriteFile(path, []byte(out), 0600); err != nil {
		t.Fatal(err)
	}
	return path
}
func TestCleanupCLIRecordsExplicitDisposableProvenance(t *testing.T) {
	base, repo, target := cleanupCLIDirs(t)
	for _, kind := range []string{"scratch", "cache"} {
		if _, err := cleanupCLI(t, "--record", "--kind", kind, "--path", target, "--repository", repo, "--owner", "task"); err == nil {
			t.Fatal("recorded output without disposable declaration")
		}
	}
	receiptPath := cleanupCLIReceipt(t, base, repo, target)
	data, err := os.ReadFile(receiptPath)
	if err != nil {
		t.Fatal(err)
	}
	var receipt cleanup.Receipt
	if err := json.Unmarshal(data, &receipt); err != nil {
		t.Fatal(err)
	}
	if receipt.Kind != "scratch" || receipt.Path != target || receipt.Owner != "task" || receipt.GeneratedDigest == "" {
		t.Fatalf("invalid provenance %+v", receipt)
	}
}
func TestCleanupCLIRejectsIncompatibleFlags(t *testing.T) {
	base, repo, target := cleanupCLIDirs(t)
	for _, flags := range [][]string{{"--apply"}, {"--writers-stopped"}, {"--pr", "42"}, {"--stop-evidence", "done"}, {"--head", "abc"}, {"--receipt", "some.json"}} {
		args := append([]string{"--record", "--kind", "scratch", "--disposable", "--path", target, "--repository", repo, "--owner", "task"}, flags...)
		if _, err := cleanupCLI(t, args...); err == nil {
			t.Fatalf("accepted record flags: %v", flags)
		}
	}
	receipt := cleanupCLIReceipt(t, base, repo, target)
	for _, flags := range [][]string{{"--path", target}, {"--kind", "scratch"}, {"--ref", "refs/heads/main"}, {"--repository", repo}, {"--disposable"}} {
		if _, err := cleanupCLI(t, append([]string{"--receipt", receipt, "--owner", "task"}, flags...)...); err == nil {
			t.Fatalf("accepted target override: %v", flags)
		}
	}
	if _, err := cleanupCLI(t, "--owner", "task"); err == nil {
		t.Fatal("accepted missing receipt")
	}
}
func TestCleanupCLIStrictReceiptDecode(t *testing.T) {
	cases := map[string]string{"unknown-field": `{"Version":1,"unexpected":true}`, "duplicate-field": `{"Version":1,"Version":1}`, "case-duplicate": `{"Version":1,"version":1}`, "trailing-document": `{"Version":1}{}`, "trailing-garbage": `{"Version":1}garbage`, "malformed": "{", "oversized": strings.Repeat(" ", 1<<20) + `{}`}
	for name, data := range cases {
		t.Run(name, func(t *testing.T) {
			if _, err := decodeCleanupReceipt(strings.NewReader(data)); err == nil {
				t.Fatal("accepted invalid receipt")
			}
		})
	}
}
func TestCleanupCLIReceiptMustRemainOutsideTarget(t *testing.T) {
	base, repo, target := cleanupCLIDirs(t)
	path := cleanupCLIReceipt(t, base, repo, target)
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	inside := filepath.Join(target, "receipt.json")
	if err := os.WriteFile(inside, data, 0600); err != nil {
		t.Fatal(err)
	}
	if _, err := cleanupCLI(t, "--receipt", inside, "--owner", "task"); err == nil {
		t.Fatal("accepted receipt inside target")
	}
}
func TestCleanupCLIRealVisibilityPreservesActiveTarget(t *testing.T) {
	base, repo, target := cleanupCLIDirs(t)
	receipt := cleanupCLIReceipt(t, base, repo, target)
	writer := exec.Command("/bin/sh", "-c", "exec sleep 30")
	writer.Dir = target
	if err := writer.Start(); err != nil {
		t.Fatal(err)
	}
	t.Cleanup(func() { _ = writer.Process.Kill(); _ = writer.Wait() })
	out, err := cleanupCLI(t, "--receipt", receipt, "--owner", "task", "--head", "exact-completed-head", "--stop-evidence", "current human stop", "--writers-stopped", "--apply")
	if err != nil {
		t.Fatal(err)
	}
	var result cleanup.Result
	if err := json.Unmarshal([]byte(out), &result); err != nil {
		t.Fatal(err)
	}
	if result.State != "KEEP_IN_USE" && result.State != "UNAVAILABLE" {
		t.Fatalf("active process: %+v", result)
	}
	data, err := os.ReadFile(filepath.Join(target, "payload"))
	if err != nil || string(data) != "generated bytes" {
		t.Fatalf("active target changed: %q %v", data, err)
	}
	t.Logf("real lsof: %s (%s)", result.State, result.Reason)
}

func TestCleanupCLIRealVisibilityReclaimsIdleTaskOutput(t *testing.T) {
	base, repo, target := cleanupCLIDirs(t)
	receipt := cleanupCLIReceipt(t, base, repo, target)
	out, err := cleanupCLI(t, "--receipt", receipt, "--owner", "task", "--head", "completed-source-head", "--stop-evidence", "current human stop", "--writers-stopped", "--apply")
	if err != nil {
		t.Fatal(err)
	}
	var result cleanup.Result
	if err = json.Unmarshal([]byte(out), &result); err != nil {
		t.Fatal(err)
	}
	if result.State == "UNAVAILABLE" {
		t.Skipf("host cannot provide complete process evidence: %s", result.Reason)
	}
	if result.State != "REMOVED" || result.Bytes != int64(len("generated bytes")) {
		t.Fatalf("idle output: %+v", result)
	}
	if _, err = os.Lstat(target); !os.IsNotExist(err) {
		t.Fatalf("target retained: %v", err)
	}
	t.Log("real process inventory permitted bounded automatic recovery")
}
