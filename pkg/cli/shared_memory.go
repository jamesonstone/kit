func bindSharedMemoryFlags(cmd *cobra.Command) {
	cmd.Flags().Bool("shared-memory", false, "enable optional Notion shared-memory guidance")
	cmd.Flags().String("shared-memory-destination", "", "shared-memory destination HTTPS URL (no credentials)")
	cmd.Flags().String("shared-memory-guide", "", "operating-guide HTTPS URL (referenced, never copied)")
}

func sharedMemoryFlagsChanged(cmd *cobra.Command) bool {
	for _, name := range []string{"shared-memory", "shared-memory-destination", "shared-memory-guide"} {
		if cmd.Flags().Changed(name) {
			return true
		}
	}
	return false
}

func desiredSharedMemory(cmd *cobra.Command, old config.SharedMemoryConfig) (config.SharedMemoryConfig, error) {
	if cmd.Flags().Changed("shared-memory") {
		old.Enabled, _ = cmd.Flags().GetBool("shared-memory")
		if old.Enabled {
			old.Provider = "notion"
		}
	}
	if cmd.Flags().Changed("shared-memory-destination") {
		old.Destination, _ = cmd.Flags().GetString("shared-memory-destination")
	}
	if cmd.Flags().Changed("shared-memory-guide") {
		old.Guide, _ = cmd.Flags().GetString("shared-memory-guide")
	}
	if !old.Enabled && !cmd.Flags().Changed("shared-memory") && sharedMemoryFlagsChanged(cmd) {
		return old, fmt.Errorf("use --shared-memory to enable guidance explicitly")
	}
	return old, old.Validate()
}

const sharedMemoryBegin = "<!-- BEGIN KIT-MANAGED SHARED MEMORY -->"
const sharedMemoryEnd = "<!-- END KIT-MANAGED SHARED MEMORY -->"

func sharedMemoryBlock(c config.SharedMemoryConfig) string {
	if !c.Enabled {
		return ""
	}
	return sharedMemoryBegin + "\n<!-- Generated by Kit. Edit project guidance outside this block. -->\n\n" +
		"## Shared Memory\n\n" +
		"Notion destination: <" + c.Destination + ">. Operating guide: <" + c.Guide + ">.\n" +
		"Read the operating guide before using shared memory through an already authorized host connection. " +
		"Keep project facts in repository memory; use shared memory only as the guide permits. " +
		"If access is unavailable, report the limitation and continue repository-local work. " +
		"Do not configure credentials or MCP connections from these instructions.\n\n" + sharedMemoryEnd + "\n"
}

func planSharedMemoryInstructions(plan instructionFileWritePlan, configs []*config.Config) (instructionFileWritePlan, error) {
	if len(configs) == 0 || filepath.ToSlash(plan.relativePath) == templates.TestingReferencePath {
		return plan, nil
	}
	cfg := configs[0]
	if err := cfg.SharedMemory.Validate(); err != nil {
		return plan, err
	}
	before := ""
	if data, err := os.ReadFile(plan.absolutePath); err == nil {
		before = string(data)
	} else if !os.IsNotExist(err) {
		return plan, err
	}
	content := plan.content
	if plan.result == instructionFileSkipped {
		content = before
	}
	// An unresolved migration or symlink must keep its existing safety decision.
	if !plan.converged {
		return plan, nil
	}
	after, err := upsertSharedMemoryBlock(content, sharedMemoryBlock(cfg.SharedMemory))
	if err != nil {
		return plan, fmt.Errorf("%s: %w", plan.relativePath, err)
	}
	if after != before {
		plan.content = after
		if plan.result != instructionFileCreated {
			plan.result = instructionFileUpdated
		}
	}
	return plan, nil
}

func upsertSharedMemoryBlock(content, block string) (string, error) {
	starts, ends := strings.Count(content, sharedMemoryBegin), strings.Count(content, sharedMemoryEnd)
	if starts == 0 && ends == 0 {
		if block == "" {
			return content, nil
		}
		return strings.TrimRight(content, "\n") + "\n\n" + block, nil
	}
	start, end := strings.Index(content, sharedMemoryBegin), strings.Index(content, sharedMemoryEnd)
	if starts != 1 || ends != 1 || end < start {
		return "", fmt.Errorf("ambiguous shared-memory markers; preserve and repair manually")
	}
	end += len(sharedMemoryEnd)
	if end < len(content) && content[end] == '\n' {
		end++
	}
	if block == "" && start >= 2 && content[start-2:start] == "\n\n" {
		start--
	}
	return content[:start] + block + content[end:], nil
}
